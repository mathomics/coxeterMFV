const GESTURE_IDLE_MS = 200;
const SMALL_PIXEL_DELTA = 40;
const EPSILON = 1e-6;

const finite = (value) => typeof value === 'number' && Number.isFinite(value) ? value : 0;
const multipleOf = (value, step) => value >= step && Math.abs(value / step - Math.round(value / step)) < EPSILON;

/**
 * WheelEvent does not identify its originating device. In automatic mode,
 * conventional mouse notches zoom and continuous pixel scrolling pans. A
 * hardware/driver that emits identical events for both devices requires the
 * explicit 'mouse' or 'touchpad' preference.
 *
 * classify(event, mode) returns 'pan', 'zoom', or null for a neutral event.
 * Ctrl+wheel (including browser-generated trackpad pinch events) keeps zoom.
 * A brief pan transaction carries through larger, non-notch pixel deltas so a
 * finger movement can accelerate without switching from panning to zooming.
 * Recognisable mouse notches take precedence, even immediately after panning.
 */
export function createWheelNavigation({ now = () => globalThis.performance?.now?.() ?? Date.now() } = {}) {
  let activeMode = 'auto';
  let lastAction = null;
  let lastTime = -Infinity;

  function reset() {
    lastAction = null;
    lastTime = -Infinity;
  }

  function classify(event, mode = 'auto') {
    mode = mode === 'mouse' || mode === 'touchpad' ? mode : 'auto';
    if (mode !== activeMode) {
      activeMode = mode;
      reset();
    }
    const dx = finite(event?.deltaX);
    const dy = finite(event?.deltaY);
    if (Math.abs(dx) < EPSILON && Math.abs(dy) < EPSILON) return null;

    const time = finite(now());
    if (time < lastTime || time - lastTime > GESTURE_IDLE_MS) reset();
    const remember = (action) => {
      lastAction = action;
      lastTime = time;
      return action;
    };

    if (event?.ctrlKey) return Math.abs(dy) >= EPSILON ? remember('zoom') : null;
    if (mode === 'mouse') return Math.abs(dy) >= EPSILON ? remember('zoom') : null;
    if (mode === 'touchpad') return remember('pan');

    // Line/page units are commonly generated by conventional wheel devices.
    const deltaMode = event?.deltaMode ?? 0;
    if (deltaMode === 1 || deltaMode === 2) {
      return Math.abs(dy) >= EPSILON ? remember('zoom') : null;
    }
    // Horizontal or diagonal pixel scrolling is a pan gesture.
    if (Math.abs(dx) >= EPSILON) return remember('pan');

    const absY = Math.abs(dy);
    const legacyY = Math.abs(finite(event?.wheelDeltaY ?? event?.wheelDelta));
    const pixelNotch = multipleOf(absY, 100) || multipleOf(absY, 120);
    if (pixelNotch) return remember('zoom');

    const fractional = Math.abs(absY - Math.round(absY)) >= EPSILON;
    // Chromium can expose a legacy 120 notch even for a fractional pixel
    // scroll. Prefer the standard WheelEvent's continuous pixel measurement.
    if (fractional || absY <= SMALL_PIXEL_DELTA || event?.momentum === true) {
      return remember('pan');
    }
    const legacyNotch = multipleOf(legacyY, 120);
    if (legacyNotch) return remember('zoom');
    if (lastAction === 'pan') return remember('pan');
    // Ambiguous, large integral vertical deltas retain the existing wheel zoom.
    return remember('zoom');
  }

  return { classify, reset };
}

/** Convert scrolling units into finite screen-pixel offsets for camera panning. */
export function wheelPanDelta(event, { lineHeight = 16, pageWidth = 800, pageHeight = 800 } = {}) {
  const dx = finite(event?.deltaX);
  const dy = finite(event?.deltaY);
  const mode = event?.deltaMode ?? 0;
  const scaleX = mode === 1 ? finite(lineHeight) : mode === 2 ? finite(pageWidth) : 1;
  const scaleY = mode === 1 ? finite(lineHeight) : mode === 2 ? finite(pageHeight) : 1;
  return { x: finite(dx * scaleX), y: finite(dy * scaleY) };
}
