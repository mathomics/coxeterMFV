//! Wheel and touchpad navigation (`src/ui/wheel-navigation.js`), and the
//! stage's `wheel` handler of `src/ui/app.js`.
//!
//! A wheel event does not say which device sent it. In automatic mode,
//! conventional mouse notches zoom and continuous pixel scrolling pans. A
//! device that sends identical events for both needs the explicit `mouse` or
//! `touchpad` preference. Ctrl+wheel (including the pinch a touchpad reports
//! as one) keeps zooming. A brief pan transaction carries through larger,
//! non-notch pixel deltas so a finger movement can accelerate without
//! switching from panning to zooming; recognisable mouse notches take
//! precedence, even right after panning.

use crate::host::ScrollInput;

const GESTURE_IDLE_MS: f64 = 200.0;
const SMALL_PIXEL_DELTA: f64 = 40.0;
const EPSILON: f64 = 1e-6;

/// What a wheel event is taken for.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum WheelAction {
    Pan,
    Zoom,
}

/// `WheelEvent.deltaMode`.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum DeltaMode {
    #[default]
    Pixel,
    Line,
    Page,
}

/// The fields of a `WheelEvent` the classifier reads.
#[derive(Debug, Clone, Copy, PartialEq, Default)]
pub struct WheelInput {
    pub delta_x: f64,
    pub delta_y: f64,
    pub delta_mode: DeltaMode,
    pub ctrl_key: bool,
    /// `wheelDeltaY ?? wheelDelta` (legacy Chromium notches); 0 when absent.
    pub legacy_delta_y: f64,
    /// `event.momentum === true`.
    pub momentum: bool,
}

/// `finite(value)`: a finite number or 0.
fn finite(v: f64) -> f64 {
    if v.is_finite() { v } else { 0.0 }
}

fn multiple_of(value: f64, step: f64) -> bool {
    value >= step && (value / step - coxeter_core::js::round(value / step)).abs() < EPSILON
}

/// `createWheelNavigation({ now })`: the classifier and its pan transaction.
#[derive(Debug, Clone)]
pub struct WheelNavigation {
    active_mode: ScrollInput,
    last_action: Option<WheelAction>,
    last_time: f64,
}

impl Default for WheelNavigation {
    fn default() -> Self {
        WheelNavigation { active_mode: ScrollInput::Auto, last_action: None, last_time: f64::NEG_INFINITY }
    }
}

impl WheelNavigation {
    pub fn new() -> WheelNavigation {
        WheelNavigation::default()
    }

    /// `reset()`.
    pub fn reset(&mut self) {
        self.last_action = None;
        self.last_time = f64::NEG_INFINITY;
    }

    /// `classify(event, mode)` at time `now` (ms): pan, zoom, or nothing for a
    /// neutral event.
    pub fn classify(&mut self, event: Option<&WheelInput>, mode: ScrollInput, now: f64) -> Option<WheelAction> {
        if mode != self.active_mode {
            self.active_mode = mode;
            self.reset();
        }
        let e = event.copied().unwrap_or_default();
        let dx = finite(e.delta_x);
        let dy = finite(e.delta_y);
        if dx.abs() < EPSILON && dy.abs() < EPSILON {
            return None;
        }
        let time = finite(now);
        if time < self.last_time || time - self.last_time > GESTURE_IDLE_MS {
            self.reset();
        }
        let action = self.decide(&e, dx, dy, mode)?;
        // `remember(action)`.
        self.last_action = Some(action);
        self.last_time = time;
        Some(action)
    }

    fn decide(&self, e: &WheelInput, dx: f64, dy: f64, mode: ScrollInput) -> Option<WheelAction> {
        let zoom_if_vertical = if dy.abs() >= EPSILON { Some(WheelAction::Zoom) } else { None };
        if e.ctrl_key || mode == ScrollInput::Mouse {
            return zoom_if_vertical;
        }
        if mode == ScrollInput::Touchpad {
            return Some(WheelAction::Pan);
        }
        // Line/page units are commonly generated by conventional wheel devices.
        if matches!(e.delta_mode, DeltaMode::Line | DeltaMode::Page) {
            return zoom_if_vertical;
        }
        // Horizontal or diagonal pixel scrolling is a pan gesture.
        if dx.abs() >= EPSILON {
            return Some(WheelAction::Pan);
        }
        let abs_y = dy.abs();
        let legacy_y = finite(e.legacy_delta_y).abs();
        let pixel_notch = multiple_of(abs_y, 100.0) || multiple_of(abs_y, 120.0);
        if pixel_notch {
            return Some(WheelAction::Zoom);
        }
        let fractional = (abs_y - coxeter_core::js::round(abs_y)).abs() >= EPSILON;
        // Chromium can expose a legacy 120 notch even for a fractional pixel
        // scroll. Prefer the standard WheelEvent's continuous pixel measurement.
        if fractional || abs_y <= SMALL_PIXEL_DELTA || e.momentum {
            return Some(WheelAction::Pan);
        }
        if multiple_of(legacy_y, 120.0) {
            return Some(WheelAction::Zoom);
        }
        if self.last_action == Some(WheelAction::Pan) {
            return Some(WheelAction::Pan);
        }
        // Ambiguous, large integral vertical deltas keep the usual wheel zoom.
        Some(WheelAction::Zoom)
    }
}

/// `wheelPanDelta(event, { lineHeight, pageWidth, pageHeight })`: scrolling
/// units as finite screen-pixel offsets for panning the camera.
pub fn wheel_pan_delta(event: Option<&WheelInput>, line_height: f64, page_width: f64, page_height: f64) -> (f64, f64) {
    let e = event.copied().unwrap_or_default();
    let dx = finite(e.delta_x);
    let dy = finite(e.delta_y);
    let (sx, sy) = match e.delta_mode {
        DeltaMode::Line => (finite(line_height), finite(line_height)),
        DeltaMode::Page => (finite(page_width), finite(page_height)),
        DeltaMode::Pixel => (1.0, 1.0),
    };
    (finite(dx * sx), finite(dy * sy))
}

/// The defaults of `wheelPanDelta`: 16 px lines, 800 px pages.
pub const DEFAULT_LINE_HEIGHT: f64 = 16.0;

/// The zoom factor of one wheel step (`event.deltaY < 0 ? 1.12 : 1 / 1.12`).
pub fn wheel_zoom_factor(delta_y: f64) -> f64 {
    if delta_y < 0.0 { 1.12 } else { 1.0 / 1.12 }
}
